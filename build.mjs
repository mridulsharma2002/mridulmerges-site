// Builds public/index.html and functions/_links.js from links.json.
// Run: node build.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const site = JSON.parse(readFileSync("links.json", "utf8"));
const icons = JSON.parse(readFileSync("icons.json", "utf8"));
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const svg = (name) => `<svg viewBox="0 0 24 24" aria-hidden="true"><path d="${icons[name]}"/></svg>`;
const arrow = `<svg class="go" viewBox="0 0 24 24" aria-hidden="true"><path d="M7 17 17 7M8 7h9v9" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"/></svg>`;

const social = site.social.map((l) => `
      <li><a class="row" href="/go/${l.slug}" data-slug="${l.slug}">
        <span class="ico ico-${l.icon}">${svg(l.icon)}</span>
        <span class="txt"><b>${esc(l.label)}</b><span>${esc(l.sub)}</span></span>
        ${arrow}
      </a></li>`).join("");

const card = (p) => {
  const inner = `
        <span class="top"><b>${esc(p.label)}</b><span class="pill ${p.slug ? "live" : "now"}">${esc(p.status)}</span>${p.role ? `<span class="pill">${esc(p.role)}</span>` : ""}</span>
        <span class="desc">${esc(p.sub)}</span>`;
  return p.slug
    ? `
      <li><a class="card" href="/go/${p.slug}" data-slug="${p.slug}">${inner}
        ${arrow}</a></li>`
    : `
      <li><div class="card">${inner}</div></li>`;
};

const html = readFileSync("template.html", "utf8")
  .replaceAll("{{url}}", site.url)
  .replaceAll("{{name}}", esc(site.name))
  .replaceAll("{{handle}}", esc(site.handle))
  .replaceAll("{{tagline}}", esc(site.tagline))
  .replaceAll("{{bio}}", esc(site.bio))
  .replaceAll("{{signoff}}", esc(site.signoff))
  .replaceAll("{{note}}", esc(site.note || ""))
  .replaceAll("{{year}}", String(new Date().getFullYear()))
  .replace("{{social}}", social)
  .replace("{{building}}", site.building.map(card).join(""))
;
writeFileSync("public/index.html", html);

const map = Object.fromEntries(
  [...site.social, ...site.building].filter((l) => l.slug && l.url).map((l) => [l.slug, l.url])
);
mkdirSync("functions", { recursive: true });
writeFileSync("functions/_links.js", `// Generated by build.mjs from links.json. Do not edit by hand.\nexport const LINKS = ${JSON.stringify(map, null, 2)};\n`);
console.log("built", Object.keys(map).join(", "));
